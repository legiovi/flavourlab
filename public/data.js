// Build pairing connections from shared aroma notes
function buildPairingGraph() {
  const connections = [];
  for (let i = 0; i < INGREDIENTS.length; i++) {
    for (let j = i + 1; j < INGREDIENTS.length; j++) {
      const a = INGREDIENTS[i];
      const b = INGREDIENTS[j];
      const shared = a.aromas.filter(ar => b.aromas.includes(ar));
      if (shared.length >= 2) {
        connections.push({
          source: a.id,
          target: b.id,
          sharedAromas: shared,
          strength: shared.length
        });
      }
      // Also include explicit pairings from the book
      if (a.pairings.includes(b.id) || b.pairings.includes(a.id)) {
        const existing = connections.find(c =>
          (c.source === a.id && c.target === b.id) ||
          (c.source === b.id && c.target === a.id)
        );
        if (!existing) {
          connections.push({
            source: a.id,
            target: b.id,
            sharedAromas: shared,
            strength: Math.max(1, shared.length),
            fromBook: true
          });
        } else {
          existing.fromBook = true;
        }
      }
    }
  }
  return connections;
}

